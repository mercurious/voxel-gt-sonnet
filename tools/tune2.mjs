// Monte-Carlo tuner: random straights, closure solved exactly with two "closer" straights.
import fs from 'node:fs';
import programs from './programs.mjs';
import { turtle, normalizeArcs } from '../js/trackgen.js';
const name = process.argv[2];
const closers = JSON.parse(process.argv[3]); // indices of two adj straights solved for closure
const iters = +(process.argv[4] || 60000);
const cfg = programs[name];
let prog = normalizeArcs(cfg.prog, cfg.net).map((c) => ({ ...c }));
function rng(seed) { let s = seed >>> 0; return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296); }
const rand = rng(777);
const adjIdx = prog.map((c, i) => (c.adj ? i : -1)).filter((i) => i >= 0);
const base0 = prog.map((c) => c.s);
function endOf(p) { return turtle(p, 8, cfg.startBearing).end; }
function dirOf(i) { // unit direction of straight i
  const { end: a } = { end: turtle(prog.slice(0, i), 2, cfg.startBearing).end };
  const b = a.b * Math.PI / 180; return [Math.sin(b), Math.cos(b)];
}
const dirs = closers.map(dirOf);
function pen(p) {
  const { pts, end } = turtle(p, 12, cfg.startBearing);
  const n = pts.length - 1, step = 12, minArc = 300;
  let best = 1e9, bi = -1, bj = -1;
  const sepIdx = Math.ceil(minArc / step);
  for (let i = 0; i < n; i++) for (let j = i + sepIdx; j < n; j++) {
    if (n - (j - i) < sepIdx) continue;
    const dx = pts[i][0] - pts[j][0], dy = pts[i][1] - pts[j][1]; const d2 = dx * dx + dy * dy;
    if (d2 < best) { best = d2; bi = i; bj = j; }
  }
  let pn = 0; const ex = Math.ceil(120 / step);
  for (let i = 0; i < n; i++) for (let j = i + sepIdx; j < n; j++) {
    if (n - (j - i) < sepIdx) continue;
    if (cfg.fig8 && Math.abs(i - bi) < ex && Math.abs(j - bj) < ex) continue;
    const dx = pts[i][0] - pts[j][0], dy = pts[i][1] - pts[j][1]; const d2 = dx * dx + dy * dy;
    if (d2 < cfg.minSep ** 2) pn += (cfg.minSep - Math.sqrt(d2)) ** 2;
  }
  let ang = 90;
  if (cfg.fig8) {
    const a = pts[Math.min(bi + 1, n)], b = pts[bi], c = pts[Math.min(bj + 1, n)], e = pts[bj];
    const h1 = Math.atan2(a[0] - b[0], a[1] - b[1]), h2 = Math.atan2(c[0] - e[0], c[1] - e[1]);
    let dh = Math.abs(h1 - h2) % Math.PI; if (dh > Math.PI / 2) dh = Math.PI - dh; ang = dh * 57.3;
    pn += Math.max(0, Math.sqrt(best) - 3) ** 2 * 6 + Math.max(0, 55 - ang) ** 2 * 0.5;
  }
  return { pn, bi, bj, ang, cd: Math.sqrt(best) };
}
let best = null;
for (let it = 0; it < iters; it++) {
  const p = prog.map((c) => ({ ...c }));
  for (const i of adjIdx) p[i].s = base0[i] * (0.45 + rand() * 1.9);
  // solve closure for closers
  const e0 = endOf(p);
  const A = [[dirs[0][0], dirs[1][0]], [dirs[0][1], dirs[1][1]]];
  // e0 includes current closer lengths; want end = 0 => delta = -e (E,N)
  const rhs = [-e0.e, -e0.n];
  const det = A[0][0] * A[1][1] - A[0][1] * A[1][0];
  if (Math.abs(det) < 0.15) continue;
  const d0 = (rhs[0] * A[1][1] - A[0][1] * rhs[1]) / det, d1 = (A[0][0] * rhs[1] - rhs[0] * A[1][0]) / det;
  p[closers[0]].s += d0; p[closers[1]].s += d1;
  if (p[closers[0]].s < 40 || p[closers[1]].s < 40 || p[closers[0]].s > 900 || p[closers[1]].s > 900) continue;
  const r = pen(p);
  let reg = 0; for (const i of adjIdx) reg += ((p[i].s - base0[i]) / base0[i]) ** 2;
  const score = r.pn * 2 + reg * 30;
  if (!best || score < best.score) { best = { score, p, r, reg }; }
}
if (!best) { console.log('none'); process.exit(0); }
console.log('best', best.score.toFixed(1), JSON.stringify(best.r), 'reg', best.reg.toFixed(2), 'end', JSON.stringify(endOf(best.p)));
let out = {}; try { out = (await import('../js/trackdata.js')).default; } catch {}
out[name] = { startBearing: cfg.startBearing, prog: best.p.map((c) => { const o = { ...c }; if (o.s !== undefined) o.s = Math.round(o.s * 10) / 10; if (o.a !== undefined) o.a = Math.round(o.a * 100) / 100; return o; }) };
fs.writeFileSync(new URL('../js/trackdata.js', import.meta.url), '// generated by tools/tune.mjs / tune2.mjs\nexport default ' + JSON.stringify(out, null, 1) + ';\n');
