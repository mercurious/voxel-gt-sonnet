// Closes the turtle loops by tuning the adj:1 straights. Writes js/trackdata.js
import fs from 'node:fs';
import programs from './programs.mjs';
import { turtle, normalizeArcs } from '../js/trackgen.js';

function rng(seed) { let s = seed >>> 0; return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296); }

function cost(prog, cfg, detail) {
  const { pts, end } = turtle(prog, 8, cfg.startBearing);
  let c = end.e * end.e + end.n * end.n;
  const n = pts.length - 1, step = 8;
  const minArc = 300;
  let pen = 0, cross = null;
  let best = 1e9, bi = -1, bj = -1;
  for (let i = 0; i < n; i++) for (let j = i + Math.ceil(minArc / step); j < n; j++) {
    if (n - (j - i) < minArc / step) continue; // wrap-around neighbours
    const dx = pts[i][0] - pts[j][0], dy = pts[i][1] - pts[j][1];
    const d2 = dx * dx + dy * dy;
    if (d2 < best) { best = d2; bi = i; bj = j; }
  }
  const exclR = Math.ceil(110 / step);
  for (let i = 0; i < n; i++) for (let j = i + Math.ceil(minArc / step); j < n; j++) {
    if (n - (j - i) < minArc / step) continue;
    if (cfg.fig8 && Math.abs(i - bi) < exclR && Math.abs(j - bj) < exclR) continue;
    const dx = pts[i][0] - pts[j][0], dy = pts[i][1] - pts[j][1];
    const d2 = dx * dx + dy * dy;
    if (d2 < cfg.minSep * cfg.minSep) { const d = Math.sqrt(d2); pen += (cfg.minSep - d) ** 2; }
  }
  if (cfg.fig8) {
    const d = Math.sqrt(best);
    pen += (d > 3 ? (d - 3) ** 2 * 6 : 0);
    // want near-perpendicular crossing
    const a = pts[Math.min(bi + 1, n)], b = pts[bi], c2 = pts[Math.min(bj + 1, n)], e = pts[bj];
    const h1 = Math.atan2(a[0] - b[0], a[1] - b[1]), h2 = Math.atan2(c2[0] - e[0], c2[1] - e[1]);
    let dh = Math.abs(h1 - h2) % Math.PI; if (dh > Math.PI / 2) dh = Math.PI - dh; // 0..pi/2
    pen += ((Math.PI / 2 - dh) * 57.3 > 30 ? ((Math.PI / 2 - dh) * 57.3 - 30) ** 2 * 0.5 : 0);
    cross = { d, bi, bj, ang: dh * 57.3 };
  }
  // keep straights near design
  let reg = 0;
  prog.forEach((p, k) => { if (p.adj) reg += ((p.s - p.s0) / p.s0) ** 2; });
  const total = c + pen * 2 + reg * 40;
  if (detail) return { total, closure: Math.sqrt(c), pen, cross, end };
  return total;
}

let out = {};
try { out = (await import('../js/trackdata.js')).default; } catch {}
const only = process.argv[2];
for (const [name, cfg] of Object.entries(programs)) {
  if (only && name !== only) continue;
  let prog = normalizeArcs(cfg.prog, cfg.net, cfg.net === 0 ? 1 : 1).map((c) => (c.adj ? { ...c, s0: c.s } : c));
  const rand = rng(12345);
  let best = cost(prog, cfg);
  let bestProg = prog;
  for (let restart = 0; restart < 6; restart++) {
    let cur = restart === 0 ? prog : bestProg.map((c) => ({ ...c }));
    let cc = cost(cur, cfg);
    let sigma = 0.25;
    for (let it = 0; it < 3500; it++) {
      const cand = cur.map((c) => ({ ...c }));
      const idxs = cand.map((c, i) => (c.adj ? i : -1)).filter((i) => i >= 0);
      const k = 1 + Math.floor(rand() * 3);
      for (let m = 0; m < k; m++) {
        const i = idxs[Math.floor(rand() * idxs.length)];
        cand[i].s = Math.max(cand[i].s0 * 0.35, Math.min(cand[i].s0 * 2.4, cand[i].s * (1 + (rand() - 0.5) * 2 * sigma)));
      }
      const cn = cost(cand, cfg);
      if (cn < cc) { cur = cand; cc = cn; }
      if (it % 500 === 499) sigma = Math.max(0.01, sigma * 0.6);
    }
    if (cc < best) { best = cc; bestProg = cur; }
  }
  const d = cost(bestProg, cfg, true);
  console.log(name, 'closure', d.closure.toFixed(1), 'pen', d.pen.toFixed(1), d.cross ? JSON.stringify(d.cross) : '', 'end b', d.end.b.toFixed(1));
  const clean = bestProg.map((c) => { const o = { ...c }; delete o.s0; if (o.s !== undefined) o.s = Math.round(o.s * 10) / 10; if (o.a !== undefined) o.a = Math.round(o.a * 100) / 100; return o; });
  out[name] = { startBearing: cfg.startBearing, prog: clean };
}
fs.writeFileSync(new URL('../js/trackdata.js', import.meta.url), '// generated by tools/tune.mjs\nexport default ' + JSON.stringify(out, null, 1) + ';\n');
console.log('wrote js/trackdata.js');
